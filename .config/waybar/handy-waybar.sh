#!/bin/bash

# Path to the state file used to track whether Handy is currently recording.
STATE_FILE="/tmp/handy_recording_state"

# Path to Handy's log file, used to retrieve the transcription result after stopping.
HANDY_LOG="/home/bi/.local/share/com.pais.handy/logs/handy.log"

# --- WAYBAR STATUS CHECK ---
# Waybar calls this script with "--status" repeatedly to update the module display.
if [ "$1" == "--status" ]; then
    # If the state file exists, Handy is currently recording.
    if [ -f "$STATE_FILE" ]; then
        echo '{"text": "󰔊 REC", "class": "recording"}'
    else
        echo '{"text": "󰔊", "class": "idle"}'
    fi
    exit 0
fi

# --- TOGGLE LOGIC ---
# When called without "--status", this script toggles recording on or off.
if [ -f "$STATE_FILE" ]; then
    # --- STOP RECORDING ---
    # Remove the state file so Waybar immediately shows the idle state.
    rm "$STATE_FILE"

    # Record the current line count of Handy's log before stopping.
    # This lets us detect only the new log lines generated by this transcription.
    lines_before=$(wc -l < "$HANDY_LOG" 2>/dev/null || echo 0)

    # Tell Handy to stop recording and start transcribing.
    handy --toggle-transcription 2>/dev/null
    notify-send "Handy" "Recording stopped" -i microphone

    # Poll Handy's log for up to 15 seconds, checking every second.
    # We look for the transcription result line that appears after transcription completes.
    for i in $(seq 1 15); do
        sleep 1
        # Extract only the new lines added after we captured lines_before.
        # Match either the transcription manager result or the actions debug line.
        result=$(tail -n +$((lines_before + 1)) "$HANDY_LOG" 2>/dev/null | grep -E "Transcription result:|actions.*Transcription completed" | tail -1 | sed -e 's/.*Transcription result: //' -e "s/.*Transcription completed in [^:]*: '//" -e "s/'$//")
        if [ -n "$result" ]; then
            # Transcription result found — send it as a notification and stop polling.
            notify-send "Handy" "$result" -i microphone
            break
        fi
    done
else
    # --- START RECORDING ---
    # Create the state file so Waybar shows the recording state.
    touch "$STATE_FILE"
    # Tell Handy to start recording.
    handy --toggle-transcription 2>/dev/null
    notify-send "Handy" "Recording started" -i microphone
fi
